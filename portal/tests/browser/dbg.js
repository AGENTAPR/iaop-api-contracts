const { chromium } = require('@playwright/test');
const BASE='https://8083-agq5lpbszgbva3ygddcbarv6ea.instabox.tech';
(async()=>{
 const b=await chromium.launch({headless:true});
 const ctx=await b.newContext({ignoreHTTPSErrors:true});
 const p=await ctx.newPage();
 p.on('pageerror',e=>console.log('PAGE_ERR',String(e).slice(0,200)));
 await p.goto(BASE+'/',{waitUntil:'domcontentloaded'});
 await p.waitForSelector('input[name="username"]',{timeout:30000});
 await p.fill('input[name="username"]','demo.agent.1');
 await p.fill('input[name="password"]',process.env.DEMO_PASS);
 await p.click('#kc-login, input[type="submit"], button[type="submit"]');
 await p.waitForURL(u=>u.pathname==='/',{timeout:30000});
 const r=await p.goto(BASE+'/reference/frontend/agent-bff',{waitUntil:'domcontentloaded'});
 console.log('ref status',r.status(),'url',p.url());
 console.log('portal.js tag:',await p.evaluate(()=>!!document.querySelector('script[src*="portal.js"]')));
 const lo=await p.evaluate(()=>fetch('/auth/logout',{method:'POST',credentials:'same-origin',headers:{'Accept':'application/json'}}).then(r=>r.status).catch(e=>'ERR '+e));
 console.log('direct logout fetch status:',lo);
 await b.close();
})().catch(e=>{console.error('FATAL',e);process.exit(2)});
